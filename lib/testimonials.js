/** 3 témoignages courts pour la homepage (phrase clé + lien vers la page complète). */
export function getHomeTestimonials(count = 3) {
  const featured = testimonials.filter((t) => t.featuredOnHome && t.highlight)
  if (featured.length >= count) return featured.slice(0, count)

  const withHighlight = testimonials.filter((t) => t.highlight)
  const merged = [
    ...featured,
    ...withHighlight.filter((t) => !featured.includes(t)),
  ]
  if (merged.length >= count) return merged.slice(0, count)

  return [...testimonials]
    .sort((a, b) => new Date(b.datePublished) - new Date(a.datePublished))
    .slice(0, count)
    .map((t) => ({
      ...t,
      highlight: t.highlight || (t.reviewBody.length > 140 ? `${t.reviewBody.slice(0, 137)}…` : t.reviewBody),
    }))
}

// Fonction pour obtenir des témoignages aléatoires
export function getRandomTestimonials(count = 3) {
  const shuffled = [...testimonials].sort(() => 0.5 - Math.random())
  return shuffled.slice(0, count)
}

// Fonction pour obtenir des témoignages pertinents selon la catégorie
export function getRelevantTestimonials(category, count = 3) {
  // Mapper les catégories aux mots-clés pertinents
  const categoryKeywords = {
    'E-commerce': ['scraping', 'données', 'extraction', 'base de données'],
    'Finance': ['scraping', 'données', 'extraction', 'base de données'],
    'Artisanat': ['scraping', 'données', 'extraction', 'base de données'],
    'B2B': ['scraping', 'données', 'extraction', 'base de données', 'prospection']
  }
  
  const keywords = categoryKeywords[category] || ['scraping', 'données']
  
  // Filtrer les témoignages qui mentionnent des mots-clés pertinents
  const relevant = testimonials.filter(t => {
    const text = (t.reviewBody + ' ' + t.tags).toLowerCase()
    return keywords.some(keyword => text.includes(keyword.toLowerCase()))
  })
  
  // Si on a assez de témoignages pertinents, les retourner, sinon prendre aléatoirement
  if (relevant.length >= count) {
    return relevant.slice(0, count)
  }
  
  // Compléter avec des témoignages aléatoires
  const remaining = count - relevant.length
  const shuffled = [...testimonials].filter(t => !relevant.includes(t)).sort(() => 0.5 - Math.random())
  return [...relevant, ...shuffled.slice(0, remaining)].slice(0, count)
}

